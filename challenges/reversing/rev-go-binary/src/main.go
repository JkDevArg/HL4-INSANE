package main

import (
	"fmt"
	"os"
)

// magic is the 4-byte rotating XOR key derived from the magic constant 0xDEADBEEF.
var magic = [4]byte{0xDE, 0xAD, 0xBE, 0xEF}

// expected holds the pre-XOR'd bytes for the license key "HACKL4BS_G0_CRACK".
// To recover: password[i] = expected[i] ^ magic[i%4]
//
// Derivation (for reference — do NOT leave in production):
//   H(0x48)^0xDE=0x96  A(0x41)^0xAD=0xEC  C(0x43)^0xBE=0xFD  K(0x4B)^0xEF=0xA4
//   L(0x4C)^0xDE=0x92  4(0x34)^0xAD=0x99  B(0x42)^0xBE=0xFC  S(0x53)^0xEF=0xBC
//   _(0x5F)^0xDE=0x81  G(0x47)^0xAD=0xEA  0(0x30)^0xBE=0x8E  _(0x5F)^0xEF=0xB0
//   C(0x43)^0xDE=0x9D  R(0x52)^0xAD=0xFF  A(0x41)^0xBE=0xFF  C(0x43)^0xEF=0xAC
//   K(0x4B)^0xDE=0x95
var expected = [17]byte{
	0x96, 0xEC, 0xFD, 0xA4, 0x92, 0x99, 0xFC, 0xBC,
	0x81, 0xEA, 0x8E, 0xB0, 0x9D, 0xFF, 0xFF, 0xAC, 0x95,
}

// check validates the provided license key.
func check(input string) bool {
	if len(input) != 17 {
		return false
	}
	for i := 0; i < 17; i++ {
		if byte(input[i])^magic[i%4] != expected[i] {
			return false
		}
	}
	return true
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "Usage: ./go_checker <license-key>")
		os.Exit(1)
	}

	if check(os.Args[1]) {
		fmt.Println("VALID")
	} else {
		fmt.Println("INVALID")
	}
}
